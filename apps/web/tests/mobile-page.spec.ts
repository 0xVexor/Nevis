import { expect, test } from '@playwright/test'

test.use({ viewport: { width: 390, height: 844 }, hasTouch: true, isMobile: true, deviceScaleFactor: 3 })
test.skip(({ browserName }) => browserName === 'firefox', 'Firefox does not support the mobile browser context')

for (const lang of ['fa', 'en'] as const) {
  test(`mobile document retains its title, content and status in ${lang}`, async ({ page }) => {
    await page.addInitScript(language => localStorage.setItem('nevis.device', JSON.stringify({ lang: language, theme: language === 'fa' ? 'dark' : 'light' })), lang)
    await page.goto('/')
    await page.getByTestId('auth-switch').tap()
    await page.locator('input[name=username]').fill(`doc${Date.now().toString(36)}${Math.random().toString(36).slice(2, 5)}`)
    await page.locator('input[name=password]').fill('correct horse battery')
    await page.getByTestId('auth-submit').tap()
    await page.getByTestId('ws-new').tap()
    await page.getByTestId('mobile-home-new').tap()
    await expect(page.getByTestId('mobile-page-back')).toBeVisible()
    await expect(page.locator('.document-page .page > .toolbar')).toBeHidden()
    await page.getByTestId('title').fill(lang === 'fa' ? 'صفحه آزمایشی' : 'A mobile document')
    const editor = page.getByTestId('editor').locator('.ProseMirror')
    await editor.tap()
    await page.keyboard.insertText(lang === 'fa' ? 'محتوای یادداشت' : 'A short note')
    await page.locator('.mobile-properties summary').tap()
    await page.getByTestId('add-tag').tap()
    const tag = page.getByTestId('tag-input')
    await expect(tag).toBeFocused()
    await tag.fill(lang === 'fa' ? 'یادداشت' : 'notes')
    await tag.press('Enter')
    await expect(page.locator('.pg-props')).toContainText(lang === 'fa' ? 'یادداشت' : 'notes')
    await page.locator('.pg-props').getByRole('button', { name: lang === 'fa' ? /وضعیت: بدون وضعیت/ : /Status: No status/ }).tap()
    await page.getByRole('menuitem', { name: lang === 'fa' ? 'در حال انجام' : 'In progress' }).tap()
    await expect(page.locator('.mobile-properties summary')).toContainText(lang === 'fa' ? 'در حال انجام' : 'In progress')
    await page.locator('.mobile-properties summary').tap()
    await page.getByTestId('mobile-top-more').tap()
    await expect(page.getByTestId('share-markdown')).toBeVisible()
    await page.keyboard.press('Escape')
    await page.getByTestId('add-cover').tap()
    await page.locator('.cover-pop .ds-swatch').first().tap()
    await expect(page.locator('.document-page .cover')).toBeVisible()
    await page.locator('.cover-acts button').last().tap()
    await expect(page.locator('.document-page .cover')).toHaveCount(0)
    await page.getByTestId('mobile-page-back').tap()
    await expect(page.getByTestId('mobile-home')).toBeVisible()
    await page.getByTestId('mobile-home-latest').tap()
    await expect(page.getByTestId('title')).toHaveValue(lang === 'fa' ? 'صفحه آزمایشی' : 'A mobile document')
    await expect(editor).toContainText(lang === 'fa' ? 'محتوای یادداشت' : 'A short note')
    await expect(page.locator('.mobile-properties summary')).toContainText(lang === 'fa' ? 'در حال انجام' : 'In progress')
    await page.locator('.mobile-properties summary').tap()
    await expect(page.locator('.pg-props')).toContainText(lang === 'fa' ? 'یادداشت' : 'notes')
    await page.setViewportSize({ width: 320, height: 700 })
    expect(await page.evaluate(() => document.documentElement.scrollWidth - window.innerWidth)).toBeLessThanOrEqual(1)
  })
}

test('mobile templates expand and insert into an empty page', async ({ page }) => {
  await page.addInitScript(() => localStorage.setItem('nevis.device', JSON.stringify({ lang: 'en' })))
  await page.goto('/')
  await page.getByTestId('auth-switch').tap()
  await page.locator('input[name=username]').fill(`tpl${Date.now().toString(36)}${Math.random().toString(36).slice(2, 5)}`)
  await page.locator('input[name=password]').fill('correct horse battery')
  await page.getByTestId('auth-submit').tap()
  await page.getByTestId('ws-new').tap()
  await page.getByTestId('mobile-home-new').tap()
  const toggle = page.locator('.pg-starts-toggle')
  await expect(toggle).toHaveAttribute('aria-expanded', 'false')
  await toggle.tap()
  await expect(toggle).toHaveAttribute('aria-expanded', 'true')
  await page.locator('.pg-starts button').first().tap()
  await expect(page.getByTestId('editor').locator('.ProseMirror')).toBeFocused()
  await expect(page.getByTestId('editor').locator('.ProseMirror')).not.toHaveText('')
  await expect(toggle).toHaveCount(0)
})

test('iPhone title focus offers blocks and moves to the start of the document', async ({ page }) => {
  await page.addInitScript(() => {
    localStorage.setItem('nevis.device', JSON.stringify({ lang: 'en' }))
    Object.defineProperty(navigator, 'userAgent', { configurable: true, value: 'Mozilla/5.0 (iPhone; CPU iPhone OS 18_0 like Mac OS X) AppleWebKit/605.1.15 Version/18.0 Mobile/15E148 Safari/604.1' })
  })
  await page.goto('/')
  await page.getByTestId('auth-switch').tap()
  await page.locator('input[name=username]').fill(`ios${Date.now().toString(36)}${Math.random().toString(36).slice(2, 5)}`)
  await page.locator('input[name=password]').fill('correct horse battery')
  await page.getByTestId('auth-submit').tap()
  await page.getByTestId('ws-new').tap()
  await page.getByTestId('mobile-home-new').tap()
  const body = page.getByTestId('editor').locator('.ProseMirror')
  await expect(body).toBeVisible()
  await page.getByTestId('title').tap()
  await expect(page.getByTestId('title')).toBeFocused()
  await expect(page.getByTestId('mobile-keyboard-bar')).toBeVisible()
  await page.evaluate(() => {
    Object.defineProperty(window.visualViewport!, 'scale', { configurable: true, value: 1.2 })
    Object.defineProperty(window.visualViewport!, 'height', { configurable: true, value: 440 })
    Object.defineProperty(window.visualViewport!, 'width', { configurable: true, value: 300 })
    Object.defineProperty(window.visualViewport!, 'offsetTop', { configurable: true, value: 60 })
    Object.defineProperty(window.visualViewport!, 'offsetLeft', { configurable: true, value: 20 })
    window.visualViewport!.dispatchEvent(new Event('resize'))
  })
  await expect(page.getByTestId('mobile-keyboard-bar')).toBeVisible()
  const bar = page.getByTestId('mobile-keyboard-bar')
  await expect.poll(() => bar.evaluate(el => Math.round(el.getBoundingClientRect().bottom))).toBe(500)
  await expect.poll(() => bar.evaluate(el => Math.round(el.getBoundingClientRect().left))).toBe(20)
  await expect.poll(() => bar.evaluate(el => Math.round(el.getBoundingClientRect().width))).toBe(300)
  await page.evaluate(() => {
    Object.defineProperty(window.visualViewport!, 'offsetTop', { configurable: true, value: 100 })
    window.visualViewport!.dispatchEvent(new Event('scroll'))
  })
  await expect.poll(() => bar.evaluate(el => Math.round(el.getBoundingClientRect().bottom))).toBe(540)
  await page.getByTestId('mobile-commands').tap()
  await expect(page.getByTestId('mobile-block-options')).toBeVisible()
  await expect.poll(() => bar.evaluate(el => Math.round(el.getBoundingClientRect().bottom))).toBe(540)
  await page.getByTestId('mobile-block-heading-1').tap()
  await expect(body).toBeFocused()
  await expect(body.locator('h1')).toBeVisible()
  await page.keyboard.insertText('First block')
  await expect(body.locator('h1')).toHaveText('First block')
  await page.evaluate(() => {
    const editor = (window as any).__editor
    editor.commands.insertContent('<p>More content</p>'.repeat(25))
  })
  await expect(body.locator('p')).toHaveCount(25)
  await page.evaluate(() => new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve))))
  await page.locator('.scroller').evaluate(el => { el.scrollTop = 0 })
  await page.evaluate(async () => {
    Object.defineProperty(window.visualViewport!, 'offsetTop', { configurable: true, value: 130 })
    window.visualViewport!.dispatchEvent(new Event('scroll'))
    await new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve)))
  })
  expect(await page.locator('.scroller').evaluate(el => el.scrollTop)).toBe(0)
  await expect.poll(() => bar.evaluate(el => Math.round(el.getBoundingClientRect().bottom))).toBe(570)
  await page.setViewportSize({ width: 700, height: 390 })
  await page.evaluate(() => {
    Object.defineProperty(window.visualViewport!, 'scale', { configurable: true, value: 1 })
    Object.defineProperty(window.visualViewport!, 'height', { configurable: true, value: 230 })
    Object.defineProperty(window.visualViewport!, 'width', { configurable: true, value: 700 })
    Object.defineProperty(window.visualViewport!, 'offsetTop', { configurable: true, value: 0 })
    Object.defineProperty(window.visualViewport!, 'offsetLeft', { configurable: true, value: 0 })
    window.visualViewport!.dispatchEvent(new Event('resize'))
  })
  await expect.poll(() => bar.evaluate(el => Math.round(el.getBoundingClientRect().bottom))).toBe(230)
  await expect(body.locator('h1')).toHaveText('First block')
  await page.getByTestId('dismiss-keyboard').tap()
  await expect(page.getByTestId('mobile-keyboard-bar')).toHaveCount(0)
})
