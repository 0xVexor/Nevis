import { expect, test } from '@playwright/test'

test.use({ viewport: { width: 390, height: 844 }, hasTouch: true, isMobile: true, deviceScaleFactor: 3 })
test.skip(({ browserName }) => browserName === 'firefox', 'Firefox does not support the mobile browser context')

test('mobile home keeps a quick draft while collapsed and shows it once in recent pages', async ({ page }) => {
  await page.goto('/')
  await page.getByTestId('auth-switch').tap()
  await page.locator('input[name=username]').fill(`home${Date.now().toString(36)}${Math.random().toString(36).slice(2, 5)}`)
  await page.locator('input[name=password]').fill('correct horse battery')
  await page.getByTestId('auth-submit').tap()
  await expect(page.getByTestId('recovery')).toBeVisible()
  await page.getByTestId('ws-new').tap()
  await expect(page.getByTestId('mobile-home-empty')).toBeVisible()
  await expect(page.getByTestId('mobile-home-new')).toBeVisible()
  if (process.env.NEVIS_HOME_SHOTS) { await page.waitForTimeout(500); await page.screenshot({ path: '/tmp/nevis-home-empty-390.png' }) }
  await page.getByTestId('mobile-home-quick').tap()
  const editor = page.getByTestId('home-note-editor').locator('.ProseMirror')
  await editor.tap()
  await page.keyboard.type('یادداشت کوتاه برای مرور')
  await expect(page.getByTestId('mobile-home-latest')).toContainText('یادداشت کوتاه')
  await page.getByTestId('mobile-home-quick').tap()
  await expect(editor).toBeHidden()
  await page.getByTestId('mobile-home-quick').tap()
  await expect(editor).toContainText('یادداشت کوتاه برای مرور')
  await page.getByTestId('mobile-home-quick').tap()
  await expect(page.getByTestId('mobile-home-latest')).toContainText('یادداشت کوتاه')
  await expect(page.getByTestId('mobile-home-row').filter({ hasText: 'یادداشت کوتاه' })).toHaveCount(0)
  await page.getByTestId('mobile-home-new').tap()
  await page.getByTestId('title').fill('یادداشت دوم با عنوان طولانی برای دیدن نحوه نمایش در صفحه خانه')
  await page.getByTestId('editor').locator('.ProseMirror').tap()
  await page.keyboard.type('یک متن واقعی برای ادامه نوشتن')
  await page.locator('.mobile-nav').getByRole('button', { name: 'خانه', exact: true }).tap()
  await expect(page.getByTestId('mobile-home-latest')).toContainText('یادداشت دوم')
  await expect(page.getByTestId('mobile-home-row').filter({ hasText: 'یادداشت کوتاه' })).toHaveCount(1)
  if (process.env.NEVIS_HOME_SHOTS) { await page.locator('.scroller').evaluate(el => { el.scrollTop = 0 }); await page.waitForTimeout(800); await page.screenshot({ path: '/tmp/nevis-home-populated-390.png' }) }
  await page.setViewportSize({ width: 320, height: 700 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth - innerWidth)).toBeLessThanOrEqual(1)
  if (process.env.NEVIS_HOME_SHOTS) await page.screenshot({ path: '/tmp/nevis-home-populated-320.png' })
  await page.getByTestId('mobile-home-latest').tap()
  await expect(page.getByTestId('editor')).toBeVisible()
  await expect(page.getByTestId('editor')).toContainText('یک متن واقعی برای ادامه نوشتن')
})


test('mobile home supports English and dark appearance at narrow width', async ({ page }) => {
  await page.addInitScript(() => localStorage.setItem('nevis.device', JSON.stringify({ lang: 'en', theme: 'dark' })))
  await page.setViewportSize({ width: 320, height: 700 })
  await page.goto('/')
  await page.getByTestId('auth-switch').tap()
  await page.locator('input[name=username]').fill(`dark${Date.now().toString(36)}${Math.random().toString(36).slice(2, 5)}`)
  await page.locator('input[name=password]').fill('correct horse battery')
  await page.getByTestId('auth-submit').tap()
  await page.getByTestId('ws-new').tap()
  await expect(page.getByTestId('mobile-home')).toContainText('Your notes')
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'dark')
  expect(await page.evaluate(() => document.documentElement.scrollWidth - innerWidth)).toBeLessThanOrEqual(1)
  if (process.env.NEVIS_HOME_SHOTS) { await page.waitForTimeout(500); await page.screenshot({ path: '/tmp/nevis-home-dark-320.png' }) }
})

test('keyboard block menu changes only the current paragraph and keeps typing at the caret', async ({ page }) => {
  await page.goto('/')
  await page.getByTestId('auth-switch').tap()
  await page.locator('input[name=username]').fill(`keys${Date.now().toString(36)}${Math.random().toString(36).slice(2, 5)}`)
  await page.locator('input[name=password]').fill('correct horse battery')
  await page.getByTestId('auth-submit').tap()
  await page.getByTestId('ws-new').tap()
  await page.getByTestId('mobile-home-quick').tap()
  const editor = page.getByTestId('home-note-editor').locator('.ProseMirror')
  await editor.tap()
  await page.keyboard.type('اول'); await page.keyboard.press('Enter')
  await page.keyboard.type('دوم'); await page.keyboard.press('Enter')
  await page.keyboard.type('سوم')
  await editor.evaluate(el => { const text = el.querySelectorAll('p')[1]!.firstChild!; const range = document.createRange(); range.selectNodeContents(text); range.collapse(false); const selection = window.getSelection()!; selection.removeAllRanges(); selection.addRange(range) })
  await expect.poll(() => page.evaluate(() => window.getSelection()?.isCollapsed)).toBe(true)
  await page.evaluate(() => { const viewport = window.visualViewport!; Object.defineProperty(viewport, 'height', { configurable: true, value: 440 }); viewport.dispatchEvent(new Event('resize')) })
  const bar = page.getByTestId('mobile-keyboard-bar')
  await expect(bar).toBeVisible()
  await expect(page.locator('.mobile-home-composer .home-note-toolbar')).toBeHidden()
  await expect.poll(() => bar.evaluate(el => el.getBoundingClientRect().bottom)).toBe(440)
  await expect(page.getByTestId('mobile-commands')).toHaveAccessibleName('بلوک‌ها')
  if (process.env.NEVIS_HOME_SHOTS) { await page.waitForTimeout(500); await page.screenshot({ path: '/tmp/nevis-home-keyboard-390.png' }) }
  const options = page.getByTestId('mobile-block-options')
  const closedHeight = await bar.evaluate(el => el.getBoundingClientRect().height)
  await page.getByTestId('mobile-commands').tap()
  await expect(options).toBeVisible()
  expect(await bar.evaluate(el => el.getBoundingClientRect().height)).toBeGreaterThan(closedHeight)
  expect(await bar.evaluate(el => el.getBoundingClientRect().height)).toBeLessThanOrEqual(192)
  await expect.poll(async () => page.evaluate(() => {
    const caret = window.getSelection()?.getRangeAt(0).getBoundingClientRect()
    const barTop = document.querySelector('[data-testid="mobile-keyboard-bar"]')!.getBoundingClientRect().top
    return (caret?.bottom ?? Infinity) <= barTop - 6
  })).toBe(true)
  await expect(page.locator('.slash-menu')).toHaveCount(0)
  await expect(page.getByTestId('mobile-block-table')).toHaveCount(0)
  expect(await bar.evaluate(el => el.getBoundingClientRect().bottom)).toBe(440)
  if (process.env.NEVIS_HOME_SHOTS) await page.screenshot({ path: '/tmp/nevis-home-keyboard-menu-390.png' })
  const close = page.getByTestId('mobile-block-close')
  expect((await close.boundingBox())?.height).toBeGreaterThanOrEqual(44)
  await close.tap()
  await expect(options).toHaveCount(0)
  await expect(editor).toBeFocused()
  await page.getByTestId('mobile-commands').tap()
  await page.getByTestId('mobile-block-heading-2').tap()
  await expect(editor.locator('h2')).toHaveText('دوم')
  await expect(editor.locator(':scope > p').first()).toHaveText('اول')
  await expect(editor.locator(':scope > p').last()).toHaveText('سوم')
  await page.keyboard.type('!')
  await expect(editor.locator('h2')).toHaveText('دوم!')
  await page.getByTestId('mobile-commands').tap()
  await page.getByTestId('mobile-block-checklist').tap()
  await expect(editor.locator('ul[data-type="taskList"]')).toContainText('دوم!')
  await expect(editor.locator(':scope > p').first()).toHaveText('اول')
  await expect(editor.locator(':scope > p').last()).toHaveText('سوم')
  await page.keyboard.type('؟')
  await expect(editor.locator('ul[data-type="taskList"]')).toContainText('دوم!؟')
  await page.setViewportSize({ width: 320, height: 700 })
  await expect(bar).toBeVisible()
  const bounds = await bar.evaluate(el => ({ width: el.getBoundingClientRect().width, children: [...el.querySelectorAll('button')].map(b => b.getBoundingClientRect().width) }))
  expect(bounds.width).toBe(320)
  expect(bounds.children.every(width => width >= 44)).toBe(true)
  await page.getByTestId('mobile-commands').tap()
  await expect(options).toBeVisible()
  await page.evaluate(() => { const viewport = window.visualViewport!; Object.defineProperty(viewport, 'height', { configurable: true, value: 300 }); viewport.dispatchEvent(new Event('resize')) })
  await expect.poll(() => bar.evaluate(el => el.getBoundingClientRect().bottom)).toBe(300)
  await expect.poll(async () => page.evaluate(() => {
    const caret = window.getSelection()?.getRangeAt(0).getBoundingClientRect()
    const barTop = document.querySelector('[data-testid="mobile-keyboard-bar"]')!.getBoundingClientRect().top
    return (caret?.bottom ?? Infinity) <= barTop - 6
  })).toBe(true)
  expect(await options.evaluate(el => el.scrollHeight > el.clientHeight)).toBe(true)
  await options.locator('button').last().scrollIntoViewIfNeeded()
  await expect(page.getByTestId('mobile-block-close')).toBeVisible()
  await page.getByTestId('mobile-block-close').tap()
  await expect(editor).toBeFocused()
  if (process.env.NEVIS_HOME_SHOTS) await page.screenshot({ path: '/tmp/nevis-home-keyboard-320.png' })
  await page.getByTestId('dismiss-keyboard').tap()
  await expect(bar).toBeHidden()
  await expect(page.locator('.mobile-nav')).toBeVisible()
})
