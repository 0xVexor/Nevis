import { expect, test } from '@playwright/test'

// ADR-0013 / ROADMAP M8b: responsive and touch. The main paths at phone width in WebKit with an iPhone-sized touch viewport: the sidebar is a
// drawer, nothing overflows sideways, a page can be made and written, and Settings works.
test.use({ viewport: { width: 390, height: 844 }, hasTouch: true, isMobile: true, deviceScaleFactor: 3 })
test.skip(({ browserName }) => browserName === 'firefox', 'Firefox does not support the mobile browser context')
test.setTimeout(90_000)

test('at phone width: the drawer, a new page, writing Persian, Settings, no sideways overflow', async ({ page }) => {
  const name = `m${Date.now().toString(36)}${Math.random().toString(36).slice(2, 5)}`
  await page.goto('/')
  await page.getByRole('button', { name: 'حساب ندارم' }).tap()
  await page.locator('input[name=username]').fill(name)
  await page.locator('input[name=password]').fill('correct horse battery')
  await page.getByTestId('auth-submit').tap()
  await expect(page.getByTestId('recovery')).toBeVisible()
  await page.getByTestId('ws-new').tap()
  await expect(page.getByTestId('home')).toBeVisible()
  await expect(page.locator('.topbar .crumb-cur')).toHaveText('خانه')

  const quickNote = page.getByTestId('home-note-editor').locator('.ProseMirror')
  await quickNote.tap()
  await page.getByTestId('mobile-commands').tap()
  await expect(page.locator('.slash-menu')).toBeVisible()
  await expect(page.locator('.slash-menu').getByRole('menuitem', { name: /^جدول/ })).toHaveCount(0)
  await page.keyboard.press('Escape')

  const overflow = () => page.evaluate(() => document.documentElement.scrollWidth - window.innerWidth)
  expect(await overflow(), 'the page scrolls sideways at 390 px').toBeLessThanOrEqual(1)

  // The writing canvas uses the full width; navigation and Pages open as drawers.
  await expect(page.locator('.side')).toBeHidden()
  await expect(page.locator('.mobile-nav')).toBeVisible()
  expect(await page.locator('.main').evaluate(el => Math.round(el.getBoundingClientRect().width))).toBe(390)
  await expect(page.locator('#workspace-context')).toBeHidden()
  await page.getByTestId('panel-toggle').tap()
  await expect(page.locator('#workspace-context')).toBeVisible()
  await page.locator('.context-backdrop').tap({ position: { x: 20, y: 300 } }).catch(() => undefined)
  await page.getByTestId('new-menu').tap()
  await page.getByTestId('new-page').tap()
  await page.waitForFunction(() => location.hash.startsWith('#/page/'))
  expect(await page.getByTestId('title').evaluate(el => parseFloat(getComputedStyle(el).fontSize))).toBe(23)
  await page.getByTestId('title').fill('یادداشت موبایل با عنوان طولانی و متن English mixed title for a narrow screen')
  expect(await page.locator('.page').evaluate(el => parseFloat(getComputedStyle(el).paddingInlineStart))).toBe(20)
  const editorBody = page.getByTestId('editor').locator('.ProseMirror')
  expect(await editorBody.evaluate(el => parseFloat(getComputedStyle(el).fontSize))).toBe(15)
  await page.evaluate(() => document.documentElement.style.setProperty('--editor-size', '20px'))
  expect(await editorBody.evaluate(el => parseFloat(getComputedStyle(el).fontSize))).toBe(20)
  await page.evaluate(() => document.documentElement.style.removeProperty('--editor-size'))
  await editorBody.tap()
  const accessory = page.getByTestId('mobile-commands')
  await expect(accessory).toBeVisible()
  await page.evaluate(() => { const viewport = window.visualViewport!; Object.defineProperty(viewport, 'height', { configurable: true, value: 440 }); viewport.dispatchEvent(new Event('resize')) })
  await expect(page.locator('.mobile-nav')).toBeHidden()
  await expect.poll(async () => accessory.evaluate(el => el.getBoundingClientRect().bottom)).toBeLessThanOrEqual(432)
  await accessory.tap()
  const commands = page.locator('.slash-menu')
  await expect(commands).toBeVisible()
  await page.evaluate(() => { const viewport = window.visualViewport!; Object.defineProperty(viewport, 'height', { configurable: true, value: 400 }); viewport.dispatchEvent(new Event('resize')) })
  await expect.poll(async () => commands.evaluate(el => el.getBoundingClientRect().bottom)).toBeLessThanOrEqual(392)
  await expect(page.locator('.mobile-nav')).toBeHidden()
  await commands.locator('[role=menuitem]').filter({ hasText: 'عنوان ۱' }).tap()
  await expect(page.getByTestId('editor').locator('h1')).toBeVisible()
  await page.evaluate(() => { const viewport = window.visualViewport!; delete (viewport as unknown as { height?: number }).height; viewport.dispatchEvent(new Event('resize')) })
  await expect(page.locator('.mobile-nav')).toBeVisible()
  await page.keyboard.type('سلام از آیفون')
  await expect(page.getByTestId('editor').locator('.ProseMirror')).toContainText('سلام از آیفون')
  expect(await overflow()).toBeLessThanOrEqual(1)
  await page.evaluate(() => { const editor = (window as any).__editor; editor.chain().focus().insertTable({ rows: 3, cols: 3, withHeaderRow: true }).run() })
  await page.locator('.ProseMirror th p').first().tap()
  const tableTools = page.locator('.table-bubble')
  await expect(tableTools).toBeVisible()
  const insertRow = tableTools.getByRole('button', { name: 'درج سطر در پایین', exact: true })
  await insertRow.tap()
  await expect(page.locator('.ProseMirror tr')).toHaveCount(4)


  await page.getByTestId('mobile-menu').tap()
  await expect(page.getByTestId('mobile-menu')).toHaveAttribute('aria-expanded', 'true')
  const drawerRow = page.getByTestId('nav-templates')
  expect(await drawerRow.evaluate(el => ({ height: el.getBoundingClientRect().height, font: parseFloat(getComputedStyle(el).fontSize) }))).toEqual({ height: 44, font: 13 })
  await expect(page.locator('.mobile-drawer .search-row')).toBeHidden()
  await page.setViewportSize({ width: 320, height: 568 })
  const drawerContent = page.locator('.mobile-drawer .side-content')
  expect(await drawerContent.evaluate(el => el.scrollHeight > el.clientHeight)).toBe(true)
  await page.getByTestId('nav-settings').scrollIntoViewIfNeeded()
  await expect(page.getByTestId('nav-settings')).toBeInViewport()
  await page.setViewportSize({ width: 390, height: 844 })
  await page.keyboard.press('Escape')
  await expect(page.getByTestId('mobile-menu')).toBeFocused()
  await page.getByTestId('mobile-menu').tap()
  await page.getByTestId('nav-settings').tap()
  await expect(page.getByTestId('settings')).toBeVisible()
  await expect(page.locator('.topbar .crumb-cur')).toHaveText('تنظیمات')
  expect(await overflow()).toBeLessThanOrEqual(1)
  await page.getByTestId('mobile-menu').tap()
  await page.getByTestId('nav-all').tap()
  await expect(page.getByTestId('all-pages-row')).toHaveCount(1)
  expect(await overflow()).toBeLessThanOrEqual(1)
  // A narrow screen retains the whole canvas and reachable navigation.
  await page.setViewportSize({ width: 320, height: 700 })
  expect(await page.locator('.main').evaluate(el => Math.round(el.getBoundingClientRect().width))).toBe(320)
  expect(await overflow()).toBeLessThanOrEqual(1)
  await page.getByTestId('new-menu').tap()
  await page.getByTestId('new-database').tap()
  await expect(page.getByTestId('db-title')).toBeVisible()
  await page.getByTestId('db-add-row').tap()
  const row = page.getByTestId('db-row').first()
  await expect(row.locator('.dv-grip')).toBeVisible()
  const boxes = await row.evaluate(el => { const a = el.querySelector('.dv-grip')!.getBoundingClientRect(); const b = el.querySelector('.ds-checkbox')!.getBoundingClientRect(); return { a: { left: a.left, right: a.right }, b: { left: b.left, right: b.right } } })
  expect(boxes.a.right <= boxes.b.left || boxes.b.right <= boxes.a.left).toBe(true)
  await row.locator('.dv-grip').tap()
  await expect(page.locator('.ds-pop')).toBeVisible()
  await page.keyboard.press('Escape')
  await row.locator('[data-prop="نام"] input').tap()
  await expect(page.getByTestId('row-peek')).toBeVisible()
  await page.getByTestId('row-editor').locator('.ProseMirror').tap()
  await page.getByTestId('mobile-commands').tap()
  await expect(page.locator('.slash-menu')).toBeVisible()
  await page.keyboard.press('Escape')
  expect(await overflow()).toBeLessThanOrEqual(1)
  // every button a thumb must hit is at least 32 px tall
  const small = await page.evaluate(() => [...document.querySelectorAll('button')].filter(b => { const r = b.getBoundingClientRect(); return r.width > 0 && r.height > 0 && r.height < 24 }).map(b => `${b.textContent?.trim().slice(0, 20)} (${b.className})`))
  expect(small, 'buttons shorter than 24 px').toEqual([])
})
