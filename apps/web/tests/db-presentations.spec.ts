import { expect, test } from '@playwright/test'
import { addProp } from './db-helpers'
import { appReady, createNew, reopenWorkspace } from './shell-helpers'

test('list and gallery preserve view settings and open rows in side peek', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: 'حساب ندارم' }).click()
  await page.locator('input[name=username]').fill(`v${Date.now().toString(36)}`)
  await page.locator('input[name=password]').fill('correct horse battery')
  await page.getByTestId('auth-submit').click()
  await page.getByTestId('ws-new').click()
  await appReady(page)
  await createNew(page, 'new-database')
  await addProp(page, 'Details', 'text')
  await page.getByTestId('db-add-row').click()
  await page.locator('[data-testid=cell][data-prop="نام"][data-row="0"] input').fill('First item')
  await page.locator('[data-testid=cell][data-prop="نام"][data-row="0"] input').blur()
  await page.locator('[data-testid=cell][data-prop="Details"][data-row="0"] input').fill('Useful detail')
  await page.locator('[data-testid=cell][data-prop="Details"][data-row="0"] input').blur()
  await page.getByTestId('add-view').click()
  await page.getByTestId('new-view-list').click()
  const list = page.getByTestId('db-list')
  await expect(list).toContainText('First item')
  await expect(list).toContainText('Useful detail')
  await list.getByRole('button', { name: 'First item' }).click()
  await expect(page.getByTestId('row-peek')).toBeVisible()
  await page.keyboard.press('Escape')
  await page.getByTestId('chip-props').click()
  await page.locator('.dv-proprow').filter({ hasText: 'Details' }).getByTestId('col-toggle').uncheck({ force: true })
  await page.keyboard.press('Escape')
  await expect(list).not.toContainText('Useful detail')
  await page.getByTestId('add-view').click()
  await page.getByTestId('new-view-gallery').click()
  const gallery = page.getByTestId('db-gallery')
  await expect(gallery).toContainText('First item')
  await expect(gallery).toContainText('Useful detail')
  await gallery.getByTestId('db-presentation-add').click()
  await expect(page.getByTestId('row-peek')).toBeVisible()
  await page.keyboard.press('Escape')
  await page.reload()
  await reopenWorkspace(page)
  await page.getByTestId('page-row').first().dblclick()
  await page.getByTestId('view-tab').filter({ hasText: 'گالری' }).click()
  await expect(gallery).toContainText('First item')
  await page.getByTestId('view-tab').filter({ hasText: 'فهرست' }).click()
  await expect(list).toContainText('First item')
  await expect(list).not.toContainText('Useful detail')
})
